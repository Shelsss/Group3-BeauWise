export default function ScannerScreen() {
	const [status, requestPermission] = ImagePicker.useCameraPermissions();
	const systemTheme = useColorScheme() ?? 'light';
	const themeMode = useThemeStore((state) => state.themeMode);
	const activeTheme = themeMode === 'system' ? systemTheme : themeMode;

	const setImageBase64 = useScanStore((state) => state.setImageBase64);
	const setImageUri = useScanStore((state) => state.setImageUri);

	const [disclaimerButtonActive, setDisclaimerButtonActive] = useState(true);
	const [disclaimerVisible, setDisclaimerVisible] = useState(false);
	const isShownDisclaimer = storage.getBoolean('analysis-disclaimer-shown');

	const showDisclaimer = () => setDisclaimerVisible(true);
	const hideDisclaimer = () => setDisclaimerVisible(false);
	const delayShowDisclaimer = useDebouncedCallback(showDisclaimer, 300);

	const handleDisclaimer = () => {
		hideDisclaimer();

		if (!isShownDisclaimer) {
			storage.set('analysis-disclaimer-shown', true);
		}
	};

	const disclaimerDisable = disclaimerButtonActive && !isShownDisclaimer;

	useEffect(() => {
		if (!isShownDisclaimer) {
			delayShowDisclaimer();
		}
	}, []);

	return (
		<View
			style={{
				flex: 1,
				backgroundColor: styles.theme.colors[activeTheme].screen_background
			}}
		>
			<View
				style={{
					backgroundColor: styles.theme.colors.primary,
					paddingHorizontal: styles.spacing.double_xl,
					paddingTop: 62,
					paddingBottom: styles.spacing.double_xxl,
					flexDirection: 'row',
					alignItems: 'center'
				}}
			>
				<View>
					<Text
						style={{
							fontFamily: styles.font.family,
							fontSize: styles.font.size.xl,
							fontWeight: styles.font.weight.bold,
							color: styles.font.colors._04
						}}
					>
						FDA Product Verifier
					</Text>

					<Text
						style={{
							fontFamily: styles.font.family,
							fontSize: styles.font.size.sm,
							fontWeight: styles.font.weight.light,
							color: styles.font.colors._04
						}}
					>
						Verify FDA Compliance Status
					</Text>
				</View>

				<TouchableOpacity
					onPress={showDisclaimer}
					activeOpacity={0.7}
					style={{ alignSelf: 'center', marginLeft: 'auto' }}
				>
					<QuestionMark
						size={styles.icon.size.xl * 1.4}
						color={styles.background_color._04}
					/>
				</TouchableOpacity>
			</View>

			<Animated.View
				style={{
					...StyleSheet.absoluteFillObject,
					position: 'absolute',
					alignSelf: 'center',
					top: 110,
					rowGap: styles.spacing.one_xxl,
					flex: 1,
					height: '100%'
				}}
			>
				{schema.map(({ name, description, action, icon, action_title }) => {
					return (
						<View
							key={name}
							style={{
								alignSelf: 'center',
								width: '92%',
								padding: styles.spacing.one_xxl,
								borderRadius: styles.border.radius.size.sm,
								backgroundColor: styles.theme.colors[activeTheme].card_background,
								borderColor: styles.theme.colors[activeTheme].card_border,
								borderWidth: 1,
								rowGap: styles.spacing.xl
							}}
						>
							<View
								style={{
									flexDirection: 'row',
									alignItems: 'center',
									columnGap: styles.spacing.lg
								}}
							>
								{icon(styles.icon.size.xl * 1.2, styles.theme.colors.primary)}

								<Text
									style={{
										color: styles.theme.colors[activeTheme].text,
										fontFamily: styles.font.family,
										fontSize: styles.font.size.lg,
										fontWeight: styles.font.weight.semi_bold
									}}
								>
									{name}
								</Text>
							</View>
							<Text
								style={{
									color: styles.theme.colors[activeTheme].text_secondary,
									fontFamily: styles.font.family,
									fontSize: styles.font.size.md,
									fontWeight: styles.font.weight.regular
								}}
							>
								{description}
							</Text>
							<TouchableOpacity
								onPress={
									name === 'Image Gallery'
										? action(setImageBase64, setImageUri)
										: name === 'Camera Scan'
											? action(status, requestPermission)
											: action()
								}
								activeOpacity={0.7}
								style={{
									backgroundColor: styles.theme.colors.primary,
									borderRadius: styles.border.radius.size.sm,
									paddingVertical: styles.spacing.xl
								}}
							>
								<Text
									style={{
										textAlign: 'center',
										color: styles.font.colors._04,
										fontFamily: styles.font.family,
										fontSize: styles.font.size.md,
										fontWeight: styles.font.weight.regular
									}}
								>
									{action_title}
								</Text>
							</TouchableOpacity>
						</View>
					);
				})}
			</Animated.View>

			<Disclaimer
				schema={disclaimerSchema}
				disclaimerVisible={disclaimerVisible}
				disabled={disclaimerDisable}
				onPress={handleDisclaimer}
				backgroundColor={styles.theme.colors.primary}
				setDisclaimerButtonActive={setDisclaimerButtonActive}
			/>
			<View
				style={{
					position: 'absolute',
					alignSelf: 'center',
					justifyContent: 'center',
					top: 710
				}}
			>
				<View
					style={{
						alignItems: 'center',
						justifyContent: 'center',
						rowGap: styles.spacing.md
					}}
				>
					<View>
						<ArrowDoubleUp
							size={styles.icon.size.xl}
							color={styles.theme.colors[activeTheme].icon}
						/>
					</View>
					<Text
						style={{
							fontFamily: styles.font.family,
							color: styles.theme.colors[activeTheme].text,
							fontSize: styles.font.size.md,
							textTransform: 'capitalize',

							textAlign: 'center'
						}}
					>
						Swipe up here to close
					</Text>
				</View>
			</View>
		</View>
	);
}
