const schema = [
	{
		name: 'Camera Scan',
		description:
			'Point your camera at any product label to instantly identify and analyze ingredients.',
		action_title: 'Open Camera',
		action: (status, requestPermission) => async () => {
			if (!status?.granted) {
				const permission = await requestPermission();

				if (!permission?.granted) {
					Alert.alert(
						'Camera Permission Blocked',
						'You have denied camera permissions. Please enable them in your device settings to use this feature.',
						[
							{ text: 'Cancel', style: 'cancel' },
							{ text: 'Open Settings', onPress: () => Linking.openSettings() }
						]
					);
				}
				return;
			}

			router.push('scanner/scan');
		},
		icon: (size, color) => <AiScan size={size} color={color} />
	},
	{
		name: 'Image Gallery',
		description:
			'Choose a photo from your gallery or library. Perfect for screenshots or saved product photos.',
		action_title: 'Choose Photo',
		action: (setImageBase64, setImageUri) => async () => {
			let result = await ImagePicker.launchImageLibraryAsync({
				mediaTypes: ['images'],
				base64: true,
				selectionLimit: 1,
				allowsEditing: true,
				allowsMultipleSelection: false,
				aspect: [3, 4],
				quality: 1
			});

			if (result.canceled) return;

			setImageBase64(result.assets[0].base64);

			router.replace({
				pathname: 'scanner/processing'
			});
		},
		icon: (size, color) => <FooImage size={size} color={color} />
	},
	{
		name: 'Manual Input',
		description:
			"Don't have a photo? Type the ingredients list manually to get a detailed ingredient analysis.",
		action_title: 'Enter Ingredients',
		action: () => () => {
			router.push('scanner/details');
		},
		icon: (size, color) => <Keyboard size={size} color={color} />
	}
];

